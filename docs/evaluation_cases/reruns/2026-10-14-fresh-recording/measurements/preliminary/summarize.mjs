// Summarizes the measurement JSON files in this directory into summary.json and summary.md.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = dirname(fileURLToPath(import.meta.url)); // preliminary/ (moved here after the main measurement was defined)
const load = (f) => JSON.parse(readFileSync(join(dir, f), "utf8"));
const methods = [
  ["insert", "insert_general"],
  ["append", "append"],
  ["popBack", "popBack"],
  ["prepend", "prepend"],
  ["setAt", "setAt"],
];
const deciding = {
  insert: ["insert-fixed-env-pair"],
  append: ["append-fixed-env-pair"],
  popBack: ["popBack-fixed-env-pair"],
  prepend: ["prepend-fixed-env-pair", "prepend-fixed-returnRef"],
  setAt: ["setAt-fixed-env-pair"],
};

const taskRow = (r) => ({
  task: r.task,
  solved_runs: r.runs.filter((x) => x.success).length,
  runs: r.runs.length,
  median_ms: r.summary.median_ms,
  min_ms: r.summary.min_ms,
  max_ms: r.summary.max_ms,
  term: r.last_rendered ? r.last_rendered.split("=\n")[1]?.trim() : null,
  error: r.runs.find((x) => !x.success)?.error ?? null,
});

const mold = (suffix, prefix = "") =>
  methods.map(([method, dirName]) => {
    const tasks = load(`${prefix}mold_${dirName}_${suffix}.json`).map(taskRow);
    return {
      method,
      tasks,
      solved: tasks.every((t) => t.solved_runs === t.runs),
      sum_of_medians_ms: Number(tasks.reduce((a, t) => a + t.median_ms, 0).toFixed(3)),
    };
  });

// The comparison uses search-only runs for both sides (see ../conditions.md, Addendum).
const baselineTasks = load("searchonly_baseline_all_cost32_timeout15s.json").map(taskRow);
const baselineThroughAdapter = load("baseline_all_cost32_timeout15s.json").map(taskRow);
const baseline = methods.map(([method]) => {
  const tasks = deciding[method].map((name) => baselineTasks.find((t) => t.task === name));
  return {
    method,
    tasks,
    solved: tasks.every((t) => t.solved_runs === t.runs),
    sum_of_medians_ms: Number(tasks.reduce((a, t) => a + t.median_ms, 0).toFixed(3)),
  };
});

const summary = {
  conditions: "see ../conditions.md",
  search_only_mold_cost32_timeout15s: mold("cost32_timeout15s", "searchonly_"),
  search_only_baseline_cost32_timeout15s: { deciding: baseline, all_tasks: baselineTasks },
  adapter_mold_cost32_timeout15s: mold("cost32_timeout15s"),
  adapter_mold_cost20_timeout2s: mold("cost20_timeout2s"),
  adapter_baseline_cost32_timeout15s_invalid: baselineThroughAdapter,
};
writeFileSync(join(dir, "summary.json"), JSON.stringify(summary, null, 2) + "\n");

const fmt = (x) => (x >= 1000 ? `${(x / 1000).toFixed(2)} s` : `${x.toFixed(2)} ms`);
const lines = [
  "# Measurement summary",
  "",
  "Generated by `summarize.mjs` from the JSON files here. Conditions: `../conditions.md`.",
  "Each task ran 5 times; \"solved\" means all 5 runs succeeded. Times are medians of 5.",
  "",
  "## Per method, search only (maxCost=32, timeoutMs=15000)",
  "",
  "| Method | MOLD solved | MOLD time (sum of helper medians) | Baseline solved | Baseline time (deciding tasks) |",
  "| --- | --- | ---: | --- | ---: |",
  ...methods.map(([method], i) => {
    const m = summary.search_only_mold_cost32_timeout15s[i];
    const b = baseline[i];
    const bs = b.tasks.map((t) => `${t.task} ${t.solved_runs}/${t.runs}`).join(", ");
    return `| ${method} | ${m.solved ? "yes" : "no"} (${m.tasks.map((t) => `${t.solved_runs}/${t.runs}`).join(", ")}) | ${fmt(m.sum_of_medians_ms)} | ${b.solved ? "yes" : "no"} (${bs}) | ${fmt(b.sum_of_medians_ms)} |`;
  }),
  "",
  "## MOLD helpers",
  "",
  "| Helper | search only, cost 32 / 15 s | through adapter (search + compile), cost 32 / 15 s | through adapter, cost 20 / 2 s (end-to-end setting) | Term |",
  "| --- | --- | --- | --- | --- |",
  ...summary.search_only_mold_cost32_timeout15s.flatMap((m, i) =>
    m.tasks.map((t, j) => {
      const a = summary.adapter_mold_cost32_timeout15s[i].tasks[j];
      const u = summary.adapter_mold_cost20_timeout2s[i].tasks[j];
      const cell = (x) => `${x.solved_runs}/${x.runs}, ${fmt(x.median_ms)} (${fmt(x.min_ms)}–${fmt(x.max_ms)})`;
      return `| ${t.task} | ${cell(t)} | ${cell(a)} | ${cell(u)} | \`${t.term}\` |`;
    }),
  ),
  "",
  "## Baseline tasks (all 16, search only)",
  "",
  "| Task | Solved | Median (min–max) |",
  "| --- | --- | --- |",
  ...baselineTasks.map((t) => `| ${t.task} | ${t.solved_runs}/${t.runs} | ${fmt(t.median_ms)} (${fmt(t.min_ms)}–${fmt(t.max_ms)}) |`),
  "",
];
writeFileSync(join(dir, "summary.md"), lines.join("\n"));
console.log(lines.join("\n"));
