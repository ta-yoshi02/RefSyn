// Summarizes the main measurement (mold_<case>.json, baseline_<method>.json) into summary.md.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = dirname(fileURLToPath(import.meta.url));
const load = (f) => JSON.parse(readFileSync(join(dir, f), "utf8"));
const methods = [
  ["insert", "insert_general"],
  ["append", "append"],
  ["popBack", "popBack"],
  ["prepend", "prepend"],
  ["setAt", "setAt"],
];
const fmt = (x) => (x >= 1000 ? `${(x / 1000).toFixed(2)} s` : `${x.toFixed(2)} ms`);
const range = (s) => `${fmt(s.median)} (${fmt(s.min)}–${fmt(s.max)})`;
const taskStats = (m) =>
  m.tasks.map((name) => {
    const runs = m.repetitions.map((r) => r.tasks.find((t) => t.task === name));
    const med = (xs) => xs.slice().sort((a, b) => a - b)[Math.floor(xs.length / 2)];
    return {
      name,
      solved: runs.filter((t) => t.success).length,
      n: runs.length,
      prepare: med(runs.map((t) => t.prepare_ms)),
      search: med(runs.map((t) => t.search_ms)),
      term: runs.find((t) => t.term)?.term ?? "-",
    };
  });

const lines = [
  "# Main measurement",
  "",
  "Conditions: `../conditions.md` (Main measurement). Generated by `summarize.mjs`.",
  "",
  "Time = escher-ts backend processing without translation to JS (spec parsing, job",
  "preparation, synthesizer construction, AscendRec search), summed over every task the",
  "method needs within one repetition; median (min–max) over 10 repetitions. It excludes Rust",
  "planning, translation, whole-method validation and the Kanon edit, so it is not the total",
  "running time of either approach. `maxCost=32`, `timeoutMs=15000` per task.",
  "",
  "| Method | MOLD tasks | MOLD solved reps | MOLD time | MOLD search only | Baseline tasks | Baseline solved reps | Baseline time | Baseline search only |",
  "| --- | ---: | ---: | ---: | ---: | --- | ---: | ---: | ---: |",
];
const rows = [];
for (const [method, dirName] of methods) {
  const m = load(`mold_${dirName}.json`);
  const b = load(`baseline_${method}.json`);
  rows.push({ method, m, b });
  lines.push(
    `| ${method} | ${m.tasks.length} | ${m.solved_repetitions}/${m.config.repetitions} | ${range(m.method_total_ms)} | ${range(m.method_search_ms)} | ${b.tasks.join(", ")} | ${b.solved_repetitions}/${b.config.repetitions} | ${range(b.method_total_ms)} | ${range(b.method_search_ms)} |`,
  );
}
lines.push("", "A repetition is solved only if every task of the method was solved in it. An unsolved baseline time is the 15 s per-task limit.", "", "## Per task (medians over 10 repetitions)", "", "| Side | Method | Task | Solved | Prepare | Search | Term |", "| --- | --- | --- | ---: | ---: | ---: | --- |");
for (const { method, m, b } of rows) {
  for (const [side, x] of [["MOLD", m], ["baseline", b]]) {
    for (const t of taskStats(x)) lines.push(`| ${side} | ${method} | ${t.name} | ${t.solved}/${t.n} | ${fmt(t.prepare)} | ${fmt(t.search)} | \`${t.term.length > 80 ? t.term.slice(0, 77) + "..." : t.term}\` |`);
  }
}
lines.push("");
writeFileSync(join(dir, "summary.md"), lines.join("\n"));
console.log(lines.join("\n"));
